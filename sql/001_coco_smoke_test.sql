-- 001_coco_smoke_test.sql
-- Smoke test: create a transient table, insert three rows, read them back.

USE ROLE COCO_LAB_ROLE;
USE WAREHOUSE COCO_LAB_WH;
USE DATABASE COCO_LAB_DB;
USE SCHEMA DEV;

CREATE OR REPLACE TRANSIENT TABLE COCO_LAB_DB.DEV.COCO_SMOKE_TEST (
    ID          NUMBER,
    DESCRIPTION VARCHAR,
    CREATED_AT  TIMESTAMP_NTZ
);

INSERT INTO COCO_LAB_DB.DEV.COCO_SMOKE_TEST (ID, DESCRIPTION, CREATED_AT) VALUES
    (1, 'First test record',  CURRENT_TIMESTAMP()::TIMESTAMP_NTZ),
    (2, 'Second test record', CURRENT_TIMESTAMP()::TIMESTAMP_NTZ),
    (3, 'Third test record',  CURRENT_TIMESTAMP()::TIMESTAMP_NTZ);

SELECT ID, DESCRIPTION, CREATED_AT
FROM COCO_LAB_DB.DEV.COCO_SMOKE_TEST
ORDER BY ID;
